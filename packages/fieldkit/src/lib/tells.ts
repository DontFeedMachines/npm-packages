export type Hit = { tell: Tell; start: number; end: number; text: string };

const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

let compiled: { tell: Tell; re: RegExp }[] | null = null;
function compile() {
  compiled ??= TELLS.map((t) => ({
    tell: t,
    re: new RegExp(
      t.regex ?? `(?<![a-z0-9])(?:${t.patterns.slice().sort((a, b) => b.length - a.length).map(esc).join("|")})(?![a-z0-9])`,
      "gi",
    ),
  }));
  return compiled;
}

export function findTells(text: string): Hit[] {
  const hits: Hit[] = [];
  for (const { tell, re } of compile()) {
    re.lastIndex = 0;
    let m: RegExpExecArray | null;
    while ((m = re.exec(text))) {
      hits.push({ tell, start: m.index, end: m.index + m[0].length, text: m[0] });
      if (m[0].length === 0) re.lastIndex++;
    }
  }
  hits.sort((a, b) => a.start - b.start || b.end - a.end);
  const out: Hit[] = [];
  let edge = -1;
  for (const h of hits) {
    if (h.start >= edge) {
      out.push(h);
      edge = h.end;
    }
  }
  return out;
}

// ghostwritten's scale: one weighted marker per 50 words reads as 100
export function synthScore(text: string, hits = findTells(text)): number {
  const words = text.split(/\s+/).filter(Boolean).length;
  if (!words) return 0;
  if (hits.some((h) => h.tell.category === "ADMISSION" && h.tell.id === "as-an-ai")) return 100;
  const weighted = hits.reduce((a, h) => a + h.tell.weight / 2, 0);
  return Math.min(Math.round((weighted / words) * 50 * 100), 100);
}

export function allPhrases(): string[] {
  return TELLS.flatMap((t) => t.patterns);
}
